import time, json, sys
from playwright.sync_api import sync_playwright
OUT = sys.argv[1]
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width':1920,'height':1080}, record_video_dir=OUT, record_video_size={'width':1920,'height':1080}, has_touch=True)
    t_ctx = time.time()
    pg = ctx.new_page(); errs=[]
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8770/stage.html'); pg.wait_for_timeout(800)
    fr = pg.frame(url=lambda u: u.endswith('index.html'))
    fr.evaluate('localStorage.clear()'); fr.evaluate('location.reload()'); pg.wait_for_timeout(1500)
    fr = pg.frame(url=lambda u: u.endswith('index.html'))
    fl = pg.frame_locator('#app')
    W = pg.wait_for_timeout
    def cap(step, c, s=''): pg.evaluate('a=>setCap(a[0],a[1],a[2])', [step, c, s])
    def left(h): pg.evaluate('h=>setLeft(h)', h)
    def tap(sel, nth=0, check=False):
        loc = fl.locator(sel).nth(nth); loc.scroll_into_view_if_needed(); W(250)
        bb = loc.bounding_box(); pg.evaluate('a=>tap(a[0],a[1])', [bb['x']+bb['width']/2, bb['y']+bb['height']/2]); W(380)
        (loc.check() if check else loc.click())
    def js(sel): fr.evaluate('s=>document.querySelector(s).click()', sel)
    t0 = time.time() - t_ctx; marks = []
    def mark(n): marks.append((n, round(time.time()-t_ctx-t0,1)))
    # 0 title
    W(4500); pg.evaluate('title(false)'); W(500)
    mark('s1')
    left('<div class="card"><h3>Today</h3><p class="big">&#8377;3,18,400</p><p>held after a festive spike. The notice says contact support; documents are asked for in rounds by email. Her evidence sits in three phone apps.</p></div>')
    cap('Step 1 · The notice', 'Riya’s settlement is on hold. She taps the notification.')
    W(3200); tap('#push'); W(2600)
    mark('s2')
    cap('Step 2 · One case', 'Every requirement, named.', 'Invoice and delivery proof for 6 payments sampled by risk policy. She can still accept payments.')
    W(5200)
    mark('s3')
    cap('Step 3 · Invoices', 'She uploads one invoice PDF.', 'AI splits it and links each page to a payment. Amounts are checked exactly.')
    W(1500); tap('.fill [data-act=pdf]'); W(1500); tap('[data-act=runPdf]'); W(3600)
    mark('s4')
    cap('Step 4 · Caught early', 'A ₹200 mismatch on #1044, caught before review.', 'She adds a note: shipping was charged separately.')
    W(2200); tap('.sheet [data-act=fix]'); W(1800); tap('.notes button', 0); W(1000); tap('[data-act=saveNote]'); W(1800)
    mark('s5')
    cap('Step 5 · Delivery', 'Delivery proof straight from Shiprocket.', 'With her consent: 5 of 6 orders verified at source. One was hand-delivered.')
    W(1200); tap('.fill [data-act=ship]'); W(1400); tap('[data-act=shipGo]'); W(3400); tap('.sheet-x'); W(900)
    mark('s6')
    cap('Step 6 · The last one', 'The customer’s WhatsApp message covers the hand delivery.', 'Screenshots are labelled merchant-supplied. 12 of 12 ready.')
    W(800); tap('.fill [data-act=wa]'); W(1200); tap('[data-f=simran]'); W(700); tap('[data-act=runWa]'); W(3000); tap('.sheet-x'); W(1800)
    mark('s7')
    cap('Step 7 · Submit', 'Review the pack, declare it genuine, submit.', 'She gets a versioned receipt that survives a refresh. Her task ends here.')
    W(800); tap('[data-act=go][data-to=review]'); W(2200); tap('#decl', check=True); W(700); tap('#submit'); W(2400)
    try:
        fl.locator('#receipt').scroll_into_view_if_needed()
    except Exception: pass
    W(2200)
    mark('s8')
    left('<div class="card" style="padding:18px"><h3>Razorpay analyst console</h3><img class="shot" src="04-console-source.png" style="width:100%"><p style="font-size:20px;margin-top:12px">Each payment’s source page, the checks run, and what was not checked.</p></div>')
    cap('Step 8 · Razorpay decides', 'The analyst accepts each requirement.', 'Release unlocks only when every requirement is accepted. AI never decides.')
    W(6000)
    js('#btn-analyst'); W(400); js('[data-act=acceptAll]'); W(300); js('[data-act=aRelease]'); W(500)
    fr.evaluate("document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape'}))"); W(600)
    if fl.locator('.stage .console, #analyst').count() and False: pass
    mark('s9')
    cap('Released', 'Settlement released.', 'Every version and decision stays on the case record.')
    tap('#push'); W(3800)
    mark('s10')
    left('<div class="card"><h3>Risk policy sets the screen</h3><p>A confidential review never shows a document request. A police hold gets its own process. KYC goes to the KYC flow.</p></div>')
    cap('Built for risk ops', 'A confidential review shows no request.', 'Only “we’re reviewing” and a next-update date. Signals are never explained.')
    js('[data-act=scenario][data-v=confidential]'); W(900); tap('#push'); W(4200)
    mark('s11')
    left('<div class="card"><h3>How we’ll measure it</h3><ul><li><b>Primary:</b> share of eligible cases with a response in 24 h judged sufficient on first review</li><li>Active task time: under 2 minutes</li><li>P90 calendar time to decision · analyst minutes per case</li><li><b>Guardrail:</b> matured fraud loss within a set margin</li></ul></div>')
    cap('The outcome', 'Faster, complete evidence. Same risk bar.', 'Merchants finish in one sitting; analysts get an indexed, versioned pack.')
    W(6500)
    pg.evaluate('''title(true,"AI does the paperwork. Razorpay makes the decision.","Settlement Review Kit &middot; working prototype &middot; Devesh, ISB PGP 2026&ndash;27","Razorpay in Your Pocket · Track 1")''')
    W(5500)
    mark('end')
    vpath = pg.video.path()
    ctx.close(); b.close()
    print(json.dumps({'t0':round(t0,2),'marks':marks,'errs':errs,'video':vpath}))
